async function sendKey(keyName) {

    const config = await browser.storage.local.get("keymap");

    const keymapIndex = parseInt(config.keymap || "0", 10);

    const code = keyMaps[keyName]?.[keymapIndex];

    if (!code) {
        console.warn(`No code for ${keyName}`);
        return;
    }

    browser.runtime.sendMessage({
        type: "sendKey",
        code: code
    });
}

async function getKeymapIndex() {
    const cfg = await browser.storage.local.get("keymap");
    return parseInt(cfg.keymap || "0", 10);
}

async function init() {

    const keymap = await getKeymapIndex();

    document.querySelectorAll("button[data-key]").forEach(btn => {

        const key = btn.dataset.key;
        const code = keyMaps[key]?.[keymap];

        // Hide unsupported buttons for this keymap
        if (!code) {
            btn.classList.add("hidden");
            return;
        }

        btn.addEventListener("click", () => sendKey(key));
    });
}

init();
